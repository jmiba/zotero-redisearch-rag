import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const normalizeVersion = (value) =>
  String(value || "")
    .trim()
    .replace(/^refs\/tags\//, "")
    .replace(/^v/, "");

const manifest = JSON.parse(readFileSync("manifest.json", "utf8"));
const manifestVersion = normalizeVersion(manifest.version);
const releaseTag = normalizeVersion(process.env.GITHUB_RELEASE_TAG);
const releaseVersion = manifestVersion || releaseTag;

if (!releaseVersion) {
  throw new Error("Could not determine release version from manifest.json or GITHUB_RELEASE_TAG.");
}

const rawBody = String(process.env.GITHUB_RELEASE_BODY || "");
const markdown = rawBody.replace(/\r\n/g, "\n").trim();
const bundledMarkdown = markdown || "This release includes improvements and fixes.";

const output = `// Auto-generated by scripts/generate-release-notes.mjs
// This file is overwritten in GitHub release workflow builds.
export const RELEASE_NOTES: { version: string; markdown: string } = ${JSON.stringify(
  {
    version: releaseVersion,
    markdown: bundledMarkdown,
  },
  null,
  2
)};
`;

writeFileSync(join("src", "releaseNotes.ts"), output, "utf8");
console.log(`Generated src/releaseNotes.ts for version ${releaseVersion}`);
